_DRAFT_MARKER = "<!-- gitlab-security-mcp:incomplete-audit -->"


def audit_report_is_draft(text: str) -> bool:
    """Distinguish persisted progress from a completed, host-written audit."""
    return text.startswith(_DRAFT_MARKER)


def persist_audit_draft(
    report: Path, root: Path, coverage: dict, progress: dict | None = None
) -> None:
    """Create the home report and append progress without replacing host findings."""
    if report.parent.resolve() != Path.home().resolve():
        raise ValueError(
            "The software audit report must be written in the home directory."
        )
    reviewed = len(coverage.get("reviews", {}))
    total = len(coverage.get("files", []))
    message = " ".join((progress or {}).get("message", "Audit started.").split())
    receipt = (
        f"\n## Review progress: {reviewed}/{total} files\n"
        f"- Updated: {datetime.now(UTC).isoformat()}\n"
        f"- Activity: {message}\n"
        f"- Completed phases: {', '.join(coverage.get('completed_phases', [])) or 'None yet'}\n"
    )
    initial = (
        f"{_DRAFT_MARKER}\n# Software audit report - INCOMPLETE\n\n"
        "**This is a progress draft, not a completed audit or a clean bill of health.**\n\n"
        f"Checkout: `{root}`\n\n"
        "Only non-generated first-party inputs are review targets. Generated source "
        "must not be reviewed, including as supporting evidence.\n\n"
        "The host AI must replace this draft with the complete findings report, "
        "then submit report_ready=True before any fix-selection window can open.\n"
        + receipt
    )
    try:
        atomic_write_text(report, initial, exclusive=True)
    except FileExistsError:
        with report.open(encoding="utf-8") as stream:
            text = stream.read()
        if not audit_report_is_draft(text):
            return
        # The server and both editor hooks persist the same batch; the AI rereads this file.
        if _progress_body(text) == _progress_body(receipt):
            return
        with report.open("a", encoding="utf-8", newline="") as stream:
            stream.write(receipt)


def _progress_body(text: str) -> list[str]:
    """Return the last progress section's counts, activity and phases, not timestamp."""
    section = text.rsplit("\n## Review progress", 1)[-1]
    return [
        line
        for line in section.strip().splitlines()
        if not line.startswith("- Updated:")
    ]


def _generated_source(path: Path) -> bool:
    """Classify generated outputs using names and bounded leading comment metadata."""
    if _GENERATED_NAME.search(path.name):
        return True
    with path.open("rb") as stream:
        prefix = stream.read(8192)
    encoding = (
        "utf-16" if prefix.startswith((b"\xff\xfe", b"\xfe\xff")) else "utf-8-sig"
    )
    header = prefix.decode(encoding, errors="replace")
    offset = 0
    while comment := _HEADER_COMMENT.match(header, offset):
        if _GENERATED_HEADER.search(comment.group()):
            return True
        offset = comment.end()
    return False


def _generated_output_paths(root: Path, exclusions: list[dict]) -> set[Path]:
    """Validate host-attested generator configuration before pruning its outputs."""
    outputs = set()
    for exclusion in exclusions:
        output = resolve_inside(root, exclusion["path"])
        if output is None or output == root.resolve() or not output.exists():
            raise ValueError(f"Invalid generated exclusion: {exclusion['path']}")
        outputs.add(output)
    for exclusion in exclusions:
        evidence = exclusion["evidence"]
        config = resolve_inside(root, evidence["path"])
        if (
            config is None
            or not config.is_file()
            or any(config.is_relative_to(output) for output in outputs)
        ):
            raise ValueError(
                f"Invalid generated exclusion evidence: {evidence['path']}"
            )
        if (
            not evidence["assessment"].strip()
            or hashlib.sha256(config.read_bytes()).hexdigest() != evidence["sha256"]
        ):
            raise ValueError(
                f"Generated exclusion needs current configuration evidence: {evidence['path']}"
            )
    return outputs


def audit_inventory(
    root: Path, *, generated_exclusions: list[dict] | None = None
) -> dict:
    """Inventory first-party review inputs without imposing a finding-count quota."""
    exclusions = generated_exclusions or []
    files, truncated = iter_files(
        root,
        excluded_dirs=_AUDIT_SKIP,
        excluded_paths=_generated_output_paths(root, exclusions),
        unbounded=True,
    )
    paths = []
    for path in files:
        relative = path.relative_to(root)
        if any(part.lower() in _AUDIT_SKIP for part in relative.parts[:-1]):
            continue
        if path.name in _LOCKFILES or path.name.endswith(
            (".min.js", ".min.css", ".lock")
        ):
            continue
        if path.suffix.lower() in _SOURCE_SUFFIXES or path.name.lower() in {
            "dockerfile",
            "agents.md",
            ".cursorrules",
            ".gitattributes",
        }:
            if not _generated_source(path):
                paths.append(relative.as_posix())
    return {
        "files": sorted(paths),
        "truncated": truncated,
        "reviews": {},
        "completed_phases": [],
        "generated_exclusions": exclusions,
    }


def record_audit_coverage(
    root: Path,
    coverage: dict,
    reviews: list[dict],
    phases: list[str],
    *,
    generated_exclusions: list[dict] | None = None,
) -> dict:
    """Validate host attestations against actual files and their current content."""
    if not set(phases) <= REVIEW_PHASES:
        raise ValueError("Unknown audit review phase.")
    exclusions = {
        item["path"]: item for item in coverage.get("generated_exclusions", [])
    }
    exclusions.update({item["path"]: item for item in generated_exclusions or []})
    current = audit_inventory(root, generated_exclusions=list(exclusions.values()))
    updated = {
        **coverage,
        "files": current["files"],
        "truncated": current["truncated"],
        "generated_exclusions": current["generated_exclusions"],
        "reviews": {
            key: value
            for key, value in coverage["reviews"].items()
            if key in current["files"]
        },
    }
    for review in reviews:
        path = resolve_inside(root, review["path"])
        if path is None or review["path"] not in updated["files"]:
            raise ValueError(f"Audit review is outside the inventory: {review['path']}")
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if review["sha256"] != digest or not review["assessment"].strip():
            raise ValueError(
                f"Audit review needs the current file hash and an assessment: {review['path']}"
            )
        updated["reviews"][review["path"]] = dict(review)
    updated["completed_phases"] = sorted(
        set(coverage["completed_phases"]) | set(phases)
    )
    return updated


def audit_coverage_gaps(root: Path, coverage: dict) -> dict:
    """Reject partial, changed, or truncated scans instead of presenting them as complete."""
    current = audit_inventory(
        root, generated_exclusions=coverage.get("generated_exclusions", [])
    )
    missing = []
    for name in current["files"]:
        review = coverage["reviews"].get(name)
        path = resolve_inside(root, name)
        if (
            review is None
            or path is None
            or review["sha256"] != hashlib.sha256(path.read_bytes()).hexdigest()
        ):
            missing.append(name)
    return {
        "remaining_files": missing,
        "total_files": len(current["files"]),
        "reviewed_files": len(current["files"]) - len(missing),
        "remaining_phases": sorted(REVIEW_PHASES - set(coverage["completed_phases"]))
        if current["files"]
        else [],
        "truncated": current["truncated"] or coverage["truncated"],
    }


_STAMP = re.compile(r"^\d{4}-\d{2}-\d{2}T\d{6}Z$")
_UNSAFE_NAME = re.compile(r'[<>:"/\\|?*\[\]\x00-\x1f]')
_SELECTABLE = re.compile(r"^###\s+(?:\d+\.\s+)?selectable findings$", re.IGNORECASE)
_ITEM = re.compile(
    r"^-\s+([A-Z][A-Z0-9]{1,8})\s+\|\s+([^|]+?)\s+\|\s+([^|]+?)\s+\|\s+(.+?)\s*$"
)


def audit_prompt() -> str:
    """Return the shipped meta-audit prompt, including its placeholders."""
    return (
        files("gitlab_security_mcp")
        .joinpath("software_audit_prompt.md")
        .read_text(encoding="utf-8")
    )


def render_audit_prompt(when: datetime, revision: str) -> str:
    """Fill the prompt's date and revision placeholders."""
    text = audit_prompt()
    return text.replace(
        "{{CURRENT_DATE}}", when.astimezone(UTC).date().isoformat()
    ).replace("{{GIT_COMMIT_SHA_OR_BRANCH}}", revision)


def project_file_name(project_path: str | None, fallback: str) -> str:
    """Return the last GitLab project segment, safe for a Windows file name."""
    raw = (project_path or "").strip().replace("\\", "/").strip("/")
    segment = raw.rsplit("/", 1)[-1] if raw else fallback
    cleaned = _UNSAFE_NAME.sub("-", segment).strip(" .")
    return cleaned or "gitlab-project"


def audit_report_path(project_name: str, when: datetime) -> Path:
    """Return the home-directory report path for one project and UTC moment.

    The clock portion uses ``YYYY-MM-DDTHHMMSSZ``. That is ISO 8601 basic time,
    and it is a legal Windows file name because it contains no colons.
    """
    stamp = when.astimezone(UTC).strftime("%Y-%m-%dT%H%M%SZ")
    if _STAMP.fullmatch(stamp) is None:
        raise ValueError(f"Audit timestamp is not usable in a file name: {stamp}")
    return Path.home() / f"{project_name}_{stamp}_software_audit_report.md"


def latest_audit_report(project_name: str) -> Path | None:
    """Return the newest home-directory audit report for one project, if one exists."""
    matches = sorted(
        Path.home().glob(f"{project_name}_*_software_audit_report.md"),
        key=lambda path: path.stat().st_mtime,
    )
    return matches[-1] if matches else None


def audit_items(text: str) -> list[dict[str, str]]:
    """Return the checkbox rows from the report's selectable-findings section.

    Lines outside that section are ignored, so prose and tables cannot add a fix.
    """
    items: list[dict[str, str]] = []
    seen: set[str] = set()
    collecting = False
    for raw in text.splitlines():
        line = raw.strip()
        if _SELECTABLE.fullmatch(line):
            collecting = True
            continue
        if not collecting:
            continue
        if line.startswith("### "):
            break
        matched = _ITEM.match(line)
        if matched is None:
            continue
        item_id, severity, location, problem = (
            part.strip() for part in matched.groups()
        )
        if item_id in seen:
            continue
        seen.add(item_id)
        items.append(
            {
                "id": item_id,
                "severity": severity,
                "location": location,
                "problem": problem,
            }
        )
    return items


def audit_has_no_findings(text: str) -> bool:
    """Recognize an explicit empty selectable section, not missing report content."""
    collecting = False
    content = []
    for raw in text.splitlines():
        line = raw.strip()
        if _SELECTABLE.fullmatch(line):
            collecting = True
            continue
        if collecting:
            if line.startswith("### "):
                break
            if line:
                content.append(line)
    return content == ["No selectable findings."]


def choice_labels() -> list[dict[str, str]]:
    """Return the three closing questions in display order."""
    return [{"id": key, "label": label} for key, label in _CHOICES.items()]


def normalize_choice(value: str | None) -> str | None:
    """Return a known choice id, or None when the value is absent or unknown."""
    if value in _CHOICES or value == "generate_report":
        return value
    return None
